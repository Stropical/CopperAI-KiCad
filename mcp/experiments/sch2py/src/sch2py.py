"""
sch2py: Convert KiCad schematic (.kicad_sch) → compact Python DSL script.

The generated Python is ~10-50x shorter than the original S-expression,
retaining full circuit topology (components + nets) but dropping:
  - Symbol geometry (polylines, arcs, rectangles)
  - Exact wire coordinates
  - UUIDs
  - Cosmetic properties (font sizes, colors, footprint filters)
  - KiCad internal metadata

Usage:
    python -m sch2py.sch2py input.kicad_sch [output.py]
    python -m sch2py.sch2py input.kicad_sch --compact   # topology-only, no coords
    python -m sch2py.sch2py input.kicad_sch --stats     # token count comparison
"""

from __future__ import annotations

import re
import sys
import textwrap
from pathlib import Path
from typing import Dict, List, Optional, Set

from .parser import parse_file, children, tag, atom, child, number as node_number
from .netlist import ComponentInstance, Net, NetPin, extract_netlist

# ---------------------------------------------------------------------------
# Properties to keep (everything else is dropped)
# ---------------------------------------------------------------------------

KEEP_PROPS = {
    "Reference", "Value", "Footprint",
    "Sim.Device", "Sim.Type", "Sim.Params", "Sim.Name", "Sim.Library", "Sim.Pins",
    "Spice_Primitive", "Spice_Model", "Spice_Netlist_Enabled",
}

GENERIC_LIBS = {
    "Device:R": "R",
    "Device:C": "C",
    "Device:L": "L",
    "Device:D": "D",
    "Device:LED": "D",
    "Device:Q_NPN_BCE": "Q",
    "Device:Q_PNP_BCE": "Q",
    "power:GND": None,  # represented as sch.gnd()
    "power:VCC": None,
    "power:+3V3": None,
    "power:+5V": None,
    "power:PWR_FLAG": None,
}

POWER_NETS = {"GND", "VSS", "VCC", "VDD", "+3V3", "+5V", "+3.3V", "+12V", "-12V", "-5V", "GNDD", "AGND"}


def _is_power_net(name: str) -> bool:
    return name in POWER_NETS or name.startswith("+") or name.startswith("-")


# ---------------------------------------------------------------------------
# Emit helpers
# ---------------------------------------------------------------------------

def _py_str(s: str) -> str:
    """Format a string for Python source."""
    if not s or s == "~":
        return '""'
    if '"' in s:
        return repr(s)
    return f'"{s}"'


def _prop_kwargs(props: Dict[str, str], lib_id: str) -> str:
    """Build keyword args string for sim/spice properties."""
    out_parts = []
    for k, v in props.items():
        if k in ("Reference", "Value", "Footprint"):
            continue
        if k not in KEEP_PROPS:
            continue
        key = k.replace(".", "_").replace("-", "_")
        out_parts.append(f'{key}={_py_str(v)}')
    return ", ".join(out_parts)


# ---------------------------------------------------------------------------
# Main emitter
# ---------------------------------------------------------------------------

def emit_python(comps: List[ComponentInstance], nets: List[Net],
                name: str = "circuit",
                include_coords: bool = True,
                sim_directives: List[str] | None = None) -> str:
    lines: List[str] = []

    lines.append(f'"""')
    lines.append(f'KiCad schematic: {name}')
    lines.append(f'Generated by sch2py. Edit freely.')
    lines.append(f'"""')
    lines.append("")
    lines.append("from sch2py.runtime import Circuit")
    lines.append("")
    lines.append(f'sch = Circuit({_py_str(name)})')
    lines.append("")

    # --- Component declarations ---
    lines.append("# --- Components ---")

    var_names: Dict[str, str] = {}  # ref -> python variable name
    used_vars: Dict[str, int] = {}  # var_stem -> count (for dedup)

    for comp in comps:
        ref = comp.ref
        # Variable name: "R1" -> "R1", "U1A" -> "U1A"
        # Sanitize: replace any non-identifier chars ($, ?, -, .), prefix leading digit
        var_stem = re.sub(r'[^A-Za-z0-9_]', '_', ref)
        if var_stem and var_stem[0].isdigit():
            var_stem = '_' + var_stem
        if var_stem in used_vars:
            used_vars[var_stem] += 1
            var = f"{var_stem}_{used_vars[var_stem]}"
        else:
            used_vars[var_stem] = 0
            var = var_stem
        var_names[ref] = var

        short = GENERIC_LIBS.get(comp.lib_id)
        value_str = _py_str(comp.value)
        props_str = _prop_kwargs(comp.properties, comp.lib_id)

        coord_str = ""
        if include_coords and (comp.x != 0.0 or comp.y != 0.0 or comp.rotation != 0.0):
            coord_str = f", x={comp.x}, y={comp.y}"
            if comp.rotation:
                coord_str += f", rotation={comp.rotation}"
        if comp.mirror_x:
            coord_str += ', mirror="x"'
        elif comp.mirror_y:
            coord_str += ', mirror="y"'
        fp = comp.properties.get("Footprint", "")
        if fp:
            coord_str += f', footprint={_py_str(fp)}'

        if short is None:
            # Generic or unknown - use sch.add()
            lib_str = _py_str(comp.lib_id)
            ref_str = _py_str(ref)
            if props_str:
                lines.append(f'{var} = sch.add({lib_str}, ref={ref_str}, value={value_str}{coord_str}, {props_str})')
            else:
                lines.append(f'{var} = sch.add({lib_str}, ref={ref_str}, value={value_str}{coord_str})')
        elif short in ("R", "C", "L", "D", "Q"):
            ref_str = _py_str(ref)
            if props_str:
                lines.append(f'{var} = sch.{short}({value_str}, ref={ref_str}{coord_str}, {props_str})')
            else:
                lines.append(f'{var} = sch.{short}({value_str}, ref={ref_str}{coord_str})')
        else:
            lib_str = _py_str(comp.lib_id)
            ref_str = _py_str(ref)
            if props_str:
                lines.append(f'{var} = sch.add({lib_str}, ref={ref_str}, value={value_str}{coord_str}, {props_str})')
            else:
                lines.append(f'{var} = sch.add({lib_str}, ref={ref_str}, value={value_str}{coord_str})')

    lines.append("")

    # --- Net connections ---
    lines.append("# --- Nets ---")

    seen_net_sigs: set = set()
    for net in nets:
        # Build pin list: only include pins for components we know about
        pin_args = []
        for np in net.pins:
            if np.ref in var_names:
                var = var_names[np.ref]
                pin_args.append(f'{var}["{np.pin}"]')

        if not pin_args:
            continue

        # Skip single-pin nets — they carry no connectivity information
        if len(pin_args) < 2:
            continue

        # Deduplicate nets with identical signatures (e.g. legacy PWR_FLAG duplicates)
        sig = (net.name, tuple(sorted(pin_args)))
        if sig in seen_net_sigs:
            continue
        seen_net_sigs.add(sig)

        pin_str = ", ".join(pin_args)

        if net.name == "GND":
            lines.append(f'sch.gnd({pin_str})')
        elif _is_power_net(net.name):
            lines.append(f'sch.pwr({_py_str(net.name)}, {pin_str})')
        else:
            lines.append(f'sch.net({_py_str(net.name)}, {pin_str})')

    lines.append("")

    # --- Simulation directives ---
    if sim_directives:
        lines.append("# --- Simulation ---")
        for d in sim_directives:
            d = d.strip().lstrip(".")
            parts = d.split()
            if not parts:
                continue
            if parts[0].lower() == "tran" and len(parts) >= 3:
                lines.append(f'sch.tran({_py_str(parts[1])}, {_py_str(parts[2])})')
            elif parts[0].lower() == "ac" and len(parts) >= 5:
                lines.append(f'sch.ac({_py_str(parts[2])}, {_py_str(parts[3])}, {_py_str(parts[4])})')
            else:
                lines.append(f'# .{" ".join(parts)}')
        lines.append("")

    return "\n".join(lines)


# ---------------------------------------------------------------------------
# Parse sim directives from raw schematic text nodes
# ---------------------------------------------------------------------------

def _extract_sim_directives(sch_node) -> List[str]:
    """Find .tran / .ac / .dc text directives in the schematic."""
    from .parser import children, tag, atom
    directives = []
    for node in children(sch_node):
        if tag(node) == "text":
            text = atom(node, 1) or ""
            if text.strip().startswith("."):
                directives.append(text.strip())
    return directives


# ---------------------------------------------------------------------------
# Token counting (rough estimate: split on whitespace)
# ---------------------------------------------------------------------------

def count_tokens(text: str) -> int:
    """Rough token count estimate (whitespace-split, like GPT tokenizer approximation)."""
    import re
    # Approximate: GPT tokens ~= words + punctuation groups
    return len(re.findall(r'\w+|[^\w\s]', text))


# ---------------------------------------------------------------------------
# CLI entry point
# ---------------------------------------------------------------------------

def _seed_pin_positions(sch_node) -> None:
    """
    Extract pin positions from lib_symbols and inject into py2sch.PIN_POSITIONS.
    Covers embedded symbols (pspice, custom libs) not in the system KiCad library.
    """
    from .py2sch import PIN_POSITIONS, _seeded_from_schematic
    for lib_syms in children(sch_node, "lib_symbols"):
        for sym in children(lib_syms, "symbol"):
            lib_id = atom(sym, 1)
            if not lib_id:
                continue
            # Always update — embedded schematic values override hardcoded defaults
            pin_dict: Dict[str, tuple] = {}
            _collect_sym_pins(sym, pin_dict)
            if pin_dict:
                PIN_POSITIONS[lib_id] = pin_dict
                _seeded_from_schematic.add(lib_id)


def _collect_sym_pins(node, pin_dict: dict) -> None:
    if not isinstance(node, list):
        return
    for ch in node[1:]:
        if tag(ch) == "pin":
            at = child(ch, "at")
            num = child(ch, "number")
            if at and num:
                pnum = atom(num, 1)
                px = node_number(at, 1) or 0.0
                py = node_number(at, 2) or 0.0
                if pnum:
                    pin_dict[pnum] = (px, py)
        elif tag(ch) == "symbol":
            _collect_sym_pins(ch, pin_dict)


def convert(input_path: str, output_path: Optional[str] = None,
            compact: bool = False, stats: bool = False) -> str:
    """Convert a .kicad_sch file to Python DSL. Returns the Python string."""
    path = Path(input_path)
    name = path.stem

    sch_node = parse_file(str(path))
    comps, nets = extract_netlist(sch_node)
    sim_directives = _extract_sim_directives(sch_node)

    # Seed pin positions from embedded lib_symbols so py2sch can route labels
    _seed_pin_positions(sch_node)

    py_code = emit_python(
        comps, nets,
        name=name,
        include_coords=not compact,
        sim_directives=sim_directives,
    )

    if stats:
        with open(input_path, "r") as f:
            original = f.read()
        orig_tokens = count_tokens(original)
        new_tokens = count_tokens(py_code)
        orig_lines = original.count("\n")
        new_lines = py_code.count("\n")
        print(f"\n=== Token Reduction Stats: {name} ===")
        print(f"  Original:  {orig_lines:>6} lines, ~{orig_tokens:>6} tokens")
        print(f"  Converted: {new_lines:>6} lines, ~{new_tokens:>6} tokens")
        ratio = orig_tokens / new_tokens if new_tokens else 0
        print(f"  Reduction: {ratio:.1f}x fewer tokens")
        print(f"  Components found: {len(comps)}")
        print(f"  Nets found: {len(nets)}")

    if output_path:
        Path(output_path).write_text(py_code, encoding="utf-8")
        print(f"Written: {output_path}")

    return py_code


def main() -> None:
    import argparse
    parser = argparse.ArgumentParser(description="Convert .kicad_sch to Python DSL")
    parser.add_argument("input", help="Input .kicad_sch file")
    parser.add_argument("output", nargs="?", help="Output .py file (default: stdout)")
    parser.add_argument("--compact", action="store_true", help="Omit coordinates (topology only)")
    parser.add_argument("--stats", action="store_true", help="Print token reduction statistics")
    args = parser.parse_args()

    py_code = convert(args.input, args.output, compact=args.compact, stats=args.stats)
    if not args.output:
        print(py_code)


if __name__ == "__main__":
    main()
